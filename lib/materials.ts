/**
 * 所有素材
 */
export const ALL_MATERIALS: Material[] = [
  ...ARGUMENT_MATERIALS,
  ...NARRATIVE_MATERIALS,
  ...LYRIC_MATERIALS
];

/**
 * 按类型分组
 */
export function materialsByType(): Record<MaterialType, Material[]> {
  const grouped: Record<MaterialType, Material[]> = {
    argument: [], narrative: [], lyric: []
  };
  for (const m of ALL_MATERIALS) grouped[m.type].push(m);
  return grouped;
}

/**
 * 按主题匹配素材（简单关键词匹配）
 *
 * @param topic 作文题目
 * @param type 素材类型
 * @param limit 返回数量（最多 10）
 */
export function matchMaterials(topic: string, type?: MaterialType, limit = 3): Material[] {
  const safeLimit = Math.min(10, Math.max(1, limit));
  const keywords = extractKeywords(topic);
  if (keywords.length === 0) {
    // 无关键词：返回该类型前 N 个
    return ALL_MATERIALS.filter(m => !type || m.type === type).slice(0, safeLimit);
  }

  const candidates = ALL_MATERIALS.filter(m => !type || m.type === type);

  // 评分：标题命中 + 主题命中
  const scored = candidates.map(m => {
    let score = 0;
    const allText = `${m.title}${m.brief}${m.topics.join('')}`;
    for (const kw of keywords) {
      if (allText.includes(kw)) score += 2;
      if (m.topics.some(t => t.includes(kw) || kw.includes(t))) score += 1;
    }
    return { m, score };
  })
    .filter(x => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, safeLimit)
    .map(x => x.m);

  return scored.length > 0 ? scored : candidates.slice(0, safeLimit);
}

/**
 * 简单中文关键词提取
 */
function extractKeywords(text: string): string[] {
  // 移除停用词
  const stop = new Set(['的', '了', '在', '是', '我', '你', '他', '她', '它', '我们', '他们',
    '和', '与', '或', '也', '都', '就', '还', '把', '被', '对', '从', '向', '到', '以',
    '没有', '不是', '怎样', '如何', '如何', '为什么']);

  // 简单：每个 2 字组合作为关键词
  const cleaned = text.replace(/[，。！？；：""''《》、.]/g, ' ');
  const words = new Set<string>();

  // 单字
  for (const ch of cleaned) {
    if (/[\u4e00-\u9fa5]/.test(ch) && !stop.has(ch)) {
      words.add(ch);
    }
  }
  // 双字组合
  for (let i = 0; i < cleaned.length - 1; i++) {
    const bigram = cleaned.slice(i, i + 2);
    if (/^[\u4e00-\u9fa5]{2}$/.test(bigram) && !stop.has(bigram)) {
      words.add(bigram);
    }
  }

  return Array.from(words).slice(0, 5);
}